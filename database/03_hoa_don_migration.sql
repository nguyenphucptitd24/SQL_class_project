USE KTX;

CREATE TABLE IF NOT EXISTS HoaDon (
    MaHoaDon BIGINT AUTO_INCREMENT PRIMARY KEY,
    MaSV VARCHAR(20) NOT NULL,
    Thang INT NOT NULL CHECK (Thang BETWEEN 1 AND 12),
    Nam INT NOT NULL CHECK (Nam > 2000),
    TongTien DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    TrangThai ENUM('CHUA_THANH_TOAN', 'DA_THANH_TOAN') DEFAULT 'CHUA_THANH_TOAN',
    NgayLap DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (MaSV) REFERENCES SinhVien(MaSV) ON DELETE CASCADE,
    UNIQUE (MaSV, Thang, Nam)
);

ALTER TABLE SuDungDichVu 
ADD COLUMN MaHoaDon BIGINT NULL;

ALTER TABLE SuDungDichVu 
ADD CONSTRAINT FK_SuDung_HoaDon 
FOREIGN KEY (MaHoaDon) REFERENCES HoaDon(MaHoaDon) ON DELETE SET NULL;